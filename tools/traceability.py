"""Check and render the SRS requirement traceability matrix (MBA-23, NFR-QA-09).

    python tools/traceability.py            # check, then write docs/TRACEABILITY.md
    python tools/traceability.py --check    # check only; exit 1 on problems

docs/traceability.csv is the source of truth. Each row maps one SRS
requirement to the code that implements it and the tests that prove it, or
marks it EXCLUDED with the reason.
"""

from __future__ import annotations

import ast
import csv
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "docs" / "traceability.csv"
MD_PATH = ROOT / "docs" / "TRACEABILITY.md"
SRS_PATH = ROOT / "SRS.md"
STATUSES = ("COVERED", "PARTIAL", "EXCLUDED")
_REQ = re.compile(r"^\*\*((?:REQ|NFR)-[A-Z]+-\d+|BR-\d+):\*\*\s*(.+)$")


def srs_requirements() -> dict[str, str]:
    found: dict[str, str] = {}
    for line in SRS_PATH.read_text(encoding="utf-8").splitlines():
        match = _REQ.match(line.strip())
        if match:
            found[match.group(1)] = match.group(2).strip()
    return found


def load_rows() -> list[dict[str, str]]:
    with CSV_PATH.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def _test_names(path: Path) -> set[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    names = set()
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            for item in node.body:
                if isinstance(item, ast.FunctionDef) and item.name.startswith("test_"):
                    names.add(f"{node.name}::{item.name}")
    return names


def problems() -> list[str]:
    errors: list[str] = []
    requirements = srs_requirements()
    rows = load_rows()
    ids = [row["requirement_id"] for row in rows]
    for rid, count in Counter(ids).items():
        if count > 1:
            errors.append(f"{rid}: listed {count} times")
    for rid in sorted(set(requirements) - set(ids)):
        errors.append(f"{rid}: in the SRS but not traced")
    for rid in sorted(set(ids) - set(requirements)):
        errors.append(f"{rid}: traced but not in the SRS")
    cache: dict[str, set[str]] = {}
    for row in rows:
        rid, status = row["requirement_id"], row["status"]
        if status not in STATUSES:
            errors.append(f"{rid}: unknown status {status!r}")
            continue
        codes = [c for c in row["code"].split(";") if c]
        tests = [t for t in row["tests"].split(";") if t]
        if status == "EXCLUDED":
            if not row["note"].strip():
                errors.append(f"{rid}: an exclusion needs a reason")
            continue
        if not codes or not tests:
            errors.append(f"{rid}: needs at least one code file and one test")
        if status == "PARTIAL" and not row["note"].strip():
            errors.append(f"{rid}: partial coverage needs a note")
        for code in codes:
            if not (ROOT / code).exists():
                errors.append(f"{rid}: code file {code} does not exist")
        for test in tests:
            path, _, name = test.partition("::")
            file = ROOT / path
            if not file.exists():
                errors.append(f"{rid}: test file {path} does not exist")
                continue
            if path not in cache:
                cache[path] = _test_names(file)
            if name not in cache[path]:
                errors.append(f"{rid}: test {test} does not exist")
    return errors


def render() -> str:
    requirements = srs_requirements()
    rows = load_rows()
    counts = Counter(row["status"] for row in rows)
    lines = [
        "# Requirement Traceability Matrix",
        "",
        "Generated from `docs/traceability.csv` by `python tools/traceability.py`.",
        "Do not edit this file by hand.",
        "",
        f"**{len(rows)} requirements:** {counts['COVERED']} covered by tests, "
        f"{counts['PARTIAL']} partly covered, {counts['EXCLUDED']} excluded with a reason.",
        "",
        "| Requirement | Summary | Status | Code | Tests | Note |",
        "|---|---|---|---|---|---|",
    ]
    for row in rows:
        summary = requirements.get(row["requirement_id"], "")
        summary = summary.replace("The system shall ", "").replace("|", "/")
        summary = summary[:1].upper() + summary[1:]
        if len(summary) > 90:
            summary = summary[:87].rstrip() + "..."
        code = "<br>".join(f"`{c.replace('src/medicine_booking/', '')}`"
                           for c in row["code"].split(";") if c)
        tests = "<br>".join(f"`{t.split('::')[0].replace('tests/', '')}::{t.split('::')[-1]}`"
                            for t in row["tests"].split(";") if t)
        lines.append(f"| {row['requirement_id']} | {summary} | {row['status']} | "
                     f"{code or '-'} | {tests or '-'} | {row['note'].replace('|', '/') or ''} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    errors = problems()
    for error in errors:
        print(error, file=sys.stderr)
    if errors:
        return 1
    if "--check" not in argv:
        MD_PATH.write_text(render(), encoding="utf-8")
        print(f"wrote {MD_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
